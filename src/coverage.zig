const std = @import("std");
const metadata = @import("cpu/extended_metadata.zig");

pub fn main(init: std.process.Init) !void {
    var buffer: [4096]u8 = undefined;
    var output = std.Io.File.stdout().writer(init.io, &buffer);
    const out = &output.interface;
    defer out.flush() catch {};
    try out.print("# CPU encoding coverage / CPU命令カバレッジ\n\nGenerated by `zig build coverage`: {d} canonical documented encodings.\n\n", .{metadata.definitions.len});
    try out.writeAll("Each row is checked by assembly/disassembly roundtrip, CPU decode and T-state tests. This establishes internal consistency, not complete hardware equivalence.\n\nIM0 supports injected RST instructions only. Undocumented SLL, IXH/IXL/IYH/IYL, repeated/ignored prefixes, undefined ED aliases, undocumented flags 3/5, WZ/Q and cycle-pin accuracy are outside this contract. INT/NMI acceptance has separate tests.\n\n日本語: 各行を機械的に照合します。全エンコードの実機互換性を保証する表ではありません。IM0はRST注入のみで、非公式命令・無視されるPrefix・未文書化フラグ・電気的タイミングは対象外です。\n\n| Prefix | Opcode | Assembly / operand form | Bytes | T | Taken/repeat T | Flags | Status |\n|---|---|---|---:|---:|---:|---|---|\n");
    for (metadata.definitions) |definition| {
        try out.print("| {X:0>2}{s} | {X:0>2} | `{s}` | {d} | {d} | {d} | {s} | tested |\n", .{ definition.prefix, if (definition.indexed_cb) " CB d" else "", definition.opcode, definition.pattern, definition.size(), definition.t_states, definition.taken_t_states, definition.flagEffects() });
    }
}
